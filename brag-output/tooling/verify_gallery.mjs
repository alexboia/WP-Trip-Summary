import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import fs from 'node:fs/promises';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire('C:/Users/alexandru.boia/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/package.json');
const {chromium}=require('playwright');
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const failures=[];page.on('pageerror',e=>failures.push(e.message));page.on('response',r=>{if(r.status()>=400)failures.push(`${r.status()} ${r.url()}`);});
await page.goto('http://localhost:3018');
await page.evaluate(async()=>{await document.fonts.ready;await Promise.all([...document.images].map(i=>i.decode()));});
const qa=path.join(root,'tooling/qa');await fs.mkdir(qa,{recursive:true});
await page.screenshot({path:path.join(qa,'gallery-desktop.png'),fullPage:true});
await page.evaluate(async()=>{const v=document.querySelector('video');v.muted=true;await v.play();});
await page.waitForFunction(()=>document.querySelector('video').ended,{},{timeout:40000});
const playback=await page.evaluate(()=>{const v=document.querySelector('video'),q=v.getVideoPlaybackQuality();return {duration:v.duration,ended:v.ended,currentTime:v.currentTime,width:v.videoWidth,height:v.videoHeight,totalVideoFrames:q.totalVideoFrames,droppedVideoFrames:q.droppedVideoFrames,error:v.error};});
await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(qa,'gallery-mobile.png'),fullPage:true});
const mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
await browser.close();
const result={playback,failures,mobileOverflow,audioNote:'Browser QA ran muted; stream, decode and loudness checked separately.'};
await fs.writeFile(path.join(root,'tooling/gallery-check.json'),JSON.stringify(result,null,2)+'\n');
if(failures.length||mobileOverflow||!playback.ended||playback.error)throw Error(JSON.stringify(result));
console.log(JSON.stringify(result,null,2));
